_PASS_SUBJECTS = {"Основы безопасности жизнедеятельности", "Музыка", "Изобразительное искусство"}


def subjects_for_grade(grade):
    """Список названий предметов типового плана для указанной параллели."""
    if grade in _BASE:
        return list(_BASE[grade])
    if grade <= 4:
        return list(_BASE[4])
    if grade >= 11:
        return list(_BASE[11])
    return list(_BASE.get(grade, _BASE[9]))


def all_plan_subjects():
    """Все предметы всех параллелей (для отдела образования / справочника)."""
    seen, out = set(), []
    for g in sorted(_BASE):
        for nm in _BASE[g]:
            if nm not in seen:
                seen.add(nm); out.append(nm)
    return out


def eval_for(name):
    return "pass" if name in _PASS_SUBJECTS else "points"
